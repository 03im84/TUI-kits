CATALOGOS = {"es": ES, "en": EN}
DEFAULT_LANG = "es"


class Translator:
    def __init__(self, lang: str = DEFAULT_LANG) -> None:
        self.lang = lang if lang in CATALOGOS else DEFAULT_LANG

    def __call__(self, key: str, **kwargs) -> str:
        valor = CATALOGOS[self.lang].get(key) or CATALOGOS[DEFAULT_LANG].get(key) or key
        try:
            return valor.format(**kwargs) if kwargs else valor
        except (KeyError, IndexError):
            return valor
